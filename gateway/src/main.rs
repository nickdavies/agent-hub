// --- Entrypoint ---

#[derive(Debug)]
enum RunError {
    /// Hard failure — bad input, config error, etc. Agent should deny.
    FailClosed(String),
    /// The approval authority did not produce a decision.
    ServerUnreachable(String),
}

#[derive(Debug, PartialEq)]
enum ApprovalFlowError {
    Timeout,
    Pipeline(String),
    FailClosed(String),
}

impl ApprovalFlowError {
    fn into_output(self) -> HookOutput {
        if let Self::Pipeline(reason) | Self::FailClosed(reason) = &self {
            eprintln!("[error] approvals pipeline failed: {reason}");
        }
        HookOutput {
            status: match self {
                Self::Timeout => DecisionStatus::TimedOut,
                Self::Pipeline(_) | Self::FailClosed(_) => DecisionStatus::PipelineError,
            },
            message: None,
        }
    }

    fn into_run_error(self) -> RunError {
        RunError::ServerUnreachable(match self {
            Self::Timeout => "approval timed out".to_string(),
            Self::Pipeline(reason) => reason,
            Self::FailClosed(reason) => return RunError::FailClosed(reason),
        })
    }
}

fn gateway_client(server: &str, token: Option<Secret>) -> Result<ApprovalClient, String> {
    ApprovalClient::with_options(
        server,
        token,
        ClientOptions {
            operation_timeout: Duration::from_secs(10),
            response_limit: protocol::AGENT_HUB_RUN_MAX_GATEWAY_OUTPUT_BYTES,
        },
    )
    .map_err(|error| error.to_string())
}

#[tokio::main]
async fn main() -> ExitCode {
    let cli = Cli::parse();

    match cli.command {
        Command::Approval(args) => run_approval(args).await,
        Command::StatusReport(args) => run_status_report(args).await,
        Command::Question(args) => question::run(args).await,
        Command::Supervision(args) => run_supervision(args).await,
        Command::AgentHubRunResolved(args) => run_agent_hub_run_resolved(args).await,
    }
}

